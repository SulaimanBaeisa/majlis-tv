#!/usr/bin/env bash
# Builds Mashrabiya.apk without Gradle: aapt2 -> javac -> d8 -> zipalign -> apksigner.
# Needs a JDK (17+) and the Android SDK command-line tools (build-tools 34+, platform android-34). See README.md.
set -euo pipefail
cd "$(dirname "$0")"

# --- Tools
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
if [ -z "$SDK" ]; then
  for d in "$HOME/Library/Android/sdk" "$HOME/Android/Sdk" /opt/homebrew/share/android-commandlinetools \
           /usr/local/share/android-commandlinetools /usr/lib/android-sdk; do
    if [ -d "$d/build-tools" ]; then SDK="$d"; break; fi
  done
fi
[ -n "$SDK" ] && [ -d "$SDK/build-tools" ] || { echo "Android SDK not found. Install it and set ANDROID_HOME (see README)."; exit 1; }
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
AJ="$(ls -d "$SDK"/platforms/android-*/android.jar 2>/dev/null | sort -V | tail -1 || true)"
[ -f "${AJ:-}" ] || { echo "Android platform not found. Run: sdkmanager \"platforms;android-34\""; exit 1; }
JAVAC="${JAVA_HOME:+$JAVA_HOME/bin/}javac"
KEYTOOL="${JAVA_HOME:+$JAVA_HOME/bin/}keytool"
command -v "$JAVAC" >/dev/null 2>&1 || { echo "JDK not found. Install JDK 17 and set JAVA_HOME."; exit 1; }

# --- Settings: config.properties -> Config.java
if [ ! -f config.properties ]; then
  cp config.example.properties config.properties
  echo "Created config.properties: add your TMDB key and your city there (optional), then build again."
fi
prop() {
  local v
  v="$(grep -E "^[[:space:]]*$1[[:space:]]*=" config.properties | tail -1 | cut -d= -f2- || true)"
  v="$(printf '%s' "$v" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' | tr -d '"\\')"
  printf '%s' "${v:-$2}"
}
number() {
  local v; v="$(prop "$1" "$2")"
  [[ "$v" =~ ^-?[0-9]+(\.[0-9]+)?$ ]] || { echo "config.properties: $1 must be a number (got \"$v\")" >&2; exit 1; }
  printf '%s' "$v"
}
LAT="$(number latitude 40.7128)"
LON="$(number longitude -74.0060)"
ASSIST=false; [ "$(prop disable_assistant false)" = "true" ] && ASSIST=true
CRYPTO=false; [ "$(prop show_crypto true)" = "true" ] && CRYPTO=true

rm -rf out && mkdir -p out/gen/io/freemytv out/classes
cat > out/gen/io/freemytv/Config.java <<EOF
package io.freemytv;

/** Generated by build.sh from config.properties: edit that file, not this one. */
final class Config {
    private Config() {}

    static final String TMDB_KEY = "$(prop tmdb_key '')";
    static final String TMDB_REGION = "$(prop tmdb_region US)";
    static final String LATITUDE = "$LAT";
    static final String LONGITUDE = "$LON";
    static final String CITY = "$(prop city '')";
    static final String LANGUAGE = "$(prop language auto)";
    static final String CURRENCY = "$(prop currency USD)";
    static final String TEMPERATURE = "$(prop temperature auto)";
    static final String IQAMA = "$(prop iqama 25,20,20,10,20)";
    static final boolean DISABLE_ASSISTANT = $ASSIST;
    static final boolean SHOW_CRYPTO = $CRYPTO;
}
EOF

# --- Build
"$BT/aapt2" compile --dir app/res -o out/res.zip
# Fonts uncompressed: Android reads them straight from the APK.
"$BT/aapt2" link -o out/base.apk -I "$AJ" --manifest app/AndroidManifest.xml --java out/gen out/res.zip \
  --min-sdk-version 28 --target-sdk-version 33 -A app/assets -0 ttf -0 otf
"$JAVAC" -encoding UTF-8 -nowarn -Xlint:-options -source 8 -target 8 -bootclasspath "$AJ:$BT/core-lambda-stubs.jar" -classpath "$AJ" \
  -d out/classes $(find app/src out/gen -name '*.java')
"$BT/d8" --release --min-api 28 --lib "$AJ" --output out $(find out/classes -name '*.class')
(cd out && zip -qj base.apk classes.dex)
"$BT/zipalign" -f -p 4 out/base.apk out/aligned.apk

# --- Sign
# The signing key is the app's identity: an update must be signed with the same key.
# It is NEVER in git. Precedence: MASH_KEYSTORE* env > local.properties > ~/.config/mashrabiya.
APK_NAME="Mashrabiya.apk"
RELEASE=0; [ "${1:-}" = "--release" ] && RELEASE=1
if [ "${MASH_UNSIGNED:-0}" = "1" ] || [ "${1:-}" = "--unsigned" ]; then
  cp out/aligned.apk "$APK_NAME"
  echo "BUILT $APK_NAME (unsigned, tests only)"
  exit 0
fi
if [ "$RELEASE" = "1" ] && ls app/assets/fonts/thmanyah* >/dev/null 2>&1; then
  echo "REFUSING RELEASE: private Thmanyah fonts are in app/assets/fonts (not redistributable)." >&2
  echo "Remove them (they live in ../private-fonts/) or build without --release." >&2
  exit 1
fi
lp() { grep -E "^[[:space:]]*$1[[:space:]]*=" local.properties 2>/dev/null | tail -1 | cut -d= -f2- | tr -d '"' || true; }
KS="${MASH_KEYSTORE:-$(lp keystore)}"
KS_PASS="${MASH_KEYSTORE_PASS:-$(lp ks_pass)}"
ALIAS="${MASH_KEY_ALIAS:-$(lp key_alias)}"; ALIAS="${ALIAS:-mashrabiya}"
KEY_PASS="${MASH_KEY_PASS:-$(lp key_pass)}"; KEY_PASS="${KEY_PASS:-$KS_PASS}"
if [ -z "$KS" ] && [ -f freemytv.keystore ]; then KS="$PWD/freemytv.keystore"; echo "NOTE: legacy freemytv.keystore in the repo dir; move it out (see docs/SIGNING.md)." >&2; fi
if [ -z "$KS" ] || [ ! -f "$KS" ]; then
  mkdir -p "$HOME/.config/mashrabiya"
  KS="$HOME/.config/mashrabiya/dev.keystore"
  KS_PASS="$(head -c 32 /dev/urandom | base64 | tr -d '/+=' | head -c 24)"
  "$KEYTOOL" -genkeypair -keystore "$KS" -alias mashrabiya -keyalg RSA -keysize 2048 -validity 20000 \
    -storepass "$KS_PASS" -keypass "$KS_PASS" -dname "CN=Mashrabiya (local build)" >/dev/null 2>&1
  umask 077
  printf 'keystore=%s\nks_pass=%s\nkey_alias=mashrabiya\nkey_pass=%s\n' "$KS" "$KS_PASS" "$KS_PASS" > local.properties
  echo "Created a local signing key: $KS (password in local.properties, mode 600). Keep it: updates need it."
fi
"$BT/apksigner" sign --ks "$KS" --ks-pass "pass:$KS_PASS" --ks-key-alias "$ALIAS" --key-pass "pass:$KEY_PASS" \
  --out "$APK_NAME" out/aligned.apk
"$BT/apksigner" verify --print-certs "$APK_NAME" | sed -n '1,2p'
VC=$(grep -oE 'android:versionCode="[0-9]+"' app/AndroidManifest.xml | grep -oE '[0-9]+')
VN=$(grep -oE 'android:versionName="[^"]+"' app/AndroidManifest.xml | cut -d'"' -f2)
echo "BUILT $APK_NAME versionName=$VN versionCode=$VC sha256=$(sha256sum "$APK_NAME" | cut -d' ' -f1)"
